func TestBetaOrganizationExternalStorageNewWithOptionalParams(t *testing.T) {
	baseURL := "http://localhost:4010"
	if envURL, ok := os.LookupEnv("TEST_API_BASE_URL"); ok {
		baseURL = envURL
	}
	if !testutil.CheckTestServer(t, baseURL) {
		return
	}
	client := anthropic.NewClient(
		option.WithBaseURL(baseURL),
		option.WithAPIKey("my-anthropic-api-key"),
		option.WithQuery("beta", "true"),
	)
	_, err := client.Beta.Organization.ExternalStorage.New(context.TODO(), anthropic.BetaOrganizationExternalStorageNewParams{
		ProviderConfig: anthropic.BetaOrganizationExternalStorageNewParamsProviderConfigUnion{
			OfAWS: &anthropic.BetaAWSExternalStorageConfigParam{
				AccountID:  "111122223333",
				BucketName: "acme-safety-retention",
				Region:     "us-east-2",
			},
		},
		DisplayName:   anthropic.String("x"),
		UserProfileID: anthropic.String("uprof_01SDCCSbTxrXDpWc1phhtcfK"),
		Betas:         []anthropic.AnthropicBeta{anthropic.AnthropicBetaComputerUse2024_10_22},
	})
	if err != nil {
		var apierr *anthropic.Error
		if errors.As(err, &apierr) {
			t.Log(string(apierr.DumpRequest(true)))
		}
		t.Fatalf("err should be nil: %s", err.Error())
	}
}

