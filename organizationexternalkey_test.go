func TestOrganizationExternalKeyNewWithOptionalParams(t *testing.T) {
	baseURL := "http://localhost:4010"
	if envURL, ok := os.LookupEnv("TEST_API_BASE_URL"); ok {
		baseURL = envURL
	}
	if !testutil.CheckTestServer(t, baseURL) {
		return
	}
	client := anthropic.NewClient(
		option.WithBaseURL(baseURL),
		option.WithAPIKey("my-anthropic-api-key"),
	)
	_, err := client.Organization.ExternalKeys.New(context.TODO(), anthropic.OrganizationExternalKeyNewParams{
		ProviderConfig: anthropic.OrganizationExternalKeyNewParamsProviderConfigUnion{
			OfAWS: &anthropic.AWSExternalKeyConfigParam{
				KMSARN: "arn:aws:kms:us-east-1:111122223333:key/abcd1234-5678-90ab-cdef-000011112222",
				Region: anthropic.String("us-east-1"),
			},
		},
		DisplayName: anthropic.String("x"),
		Geo:         anthropic.OrganizationExternalKeyNewParamsGeoUs,
	})
	if err != nil {
		var apierr *anthropic.Error
		if errors.As(err, &apierr) {
			t.Log(string(apierr.DumpRequest(true)))
		}
		t.Fatalf("err should be nil: %s", err.Error())
	}
}

